"""Blades and blunt weapons. Origin = the middle of the grip, business end toward +Y."""


def oval(sx, sz, loc=(0, 0, 0)):
    """Matrix that lays a Z-axis lathe along +Y and squashes it into an oval handle."""
    return xf(loc, AXIS_YF) @ Matrix.Diagonal((sx, sz, 1.0, 1.0))


# ================================================================== KNIFE (fighting knife, stacked leather handle)
@model('Knife', 'Weapons', (5.6, -1.5, WZ))
def _(m):
    prof = [(0.0, -0.0575), (0.0120, -0.0575), (0.0142, -0.0540)]
    for i in range(6):                                                           # leather washers with grooves between
        z0 = -0.0540 + i * 0.0180
        prof += [(0.0152, z0 + 0.0020), (0.0156, z0 + 0.0090), (0.0152, z0 + 0.0160), (0.0138, z0 + 0.0180)]
    prof += [(0.0130, 0.0560), (0.0, 0.0560)]
    m.lathe(prof, (0, 0, 0), Leather, seg=20, matrix=oval(0.84, 1.06))
    m.lathe([(0.0, -0.0700), (0.0100, -0.0700), (0.0150, -0.0660), (0.0150, -0.0590), (0.0125, -0.0570), (0.0, -0.0570)],
            (0, 0, 0), Parkerized, seg=20, matrix=oval(0.84, 1.06))               # pommel
    m.cyl(0.0022, 0.0290, (0, -0.0640, 0), Steel, rot=AXIS_X, seg=8)              # its pin
    m.prism([(0.0570, 0.0260), (0.0570, -0.0250), (0.0600, -0.0280), (0.0640, -0.0250), (0.0640, 0.0260),
             (0.0600, 0.0290)], 0.0125, (0, 0, 0), Parkerized, bevel=0.0025, seg=2)                 # guard
    m.blade([(0.0640, 0.0150, -0.0150, 0.0044), (0.0850, 0.0160, -0.0165, 0.0044), (0.2000, 0.0160, -0.0165, 0.0040),
             (0.2350, 0.0122, -0.0150, 0.0036), (0.2620, 0.0072, -0.0098, 0.0027), (0.2780, 0.0028, -0.0032, 0.0015),
             (0.2855, 0.0005, -0.0003, 0.0004)], Steel, flat=0.5)
    for sx in (-1, 1):                                                           # fuller
        m.box((0.0006, 0.1050, 0.0036), (sx * 0.0021, 0.1400, 0.0085), Parkerized, bevel=0.0002, seg=1, wear=0)


